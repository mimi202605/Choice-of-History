files = [
    "data/emperors/01-xia-shang-zhou-qin.json",
    "data/emperors/03-jin-nanbeichao-sui.json",
    "data/emperors/04-tang-wudai.json",
    "data/emperors/05-song-liao-jin-xixia.json",
]
total_changed = 0
for f in files:
    d = json.load(open(f, encoding="utf-8"))
    byid = {e["id"]: e for e in d["emperors"]}
    for (ff, eid), content in ENR.items():
        if ff != f.split("/")[-1]:
            continue
        e = byid.get(eid)
        if not e:
            print("WARN not found:", eid, "in", ff); continue
        changed = []
        if "background" in content:
            e["background"] = content["background"]; changed.append("bg")
        # eraContext：若原为空，填充；若提供了专用文本，填充
        ec_target = content.get("eraContext_text") or content.get("eraContext")
        if ec_target:
            e["eraContext"] = ec_target; changed.append("era")
        if "add_events" in content:
            existing = {ev["title"] for ev in e["events"]}
            added = 0
            for ev in content["add_events"]:
                if ev["title"] not in existing:
                    e["events"].append(ev); added += 1
            if added: changed.append(f"+{added}ev")
        if changed:
            total_changed += 1
            print(f"  {f.split('/')[-1]}: {e['name']} -> {changed} (bg_len={len(e['background'])}, ev={len(e['events'])})")
    json.dump(d, open(f, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("TOTAL changed:", total_changed)
