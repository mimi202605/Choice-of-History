def _jitter(base, seed):
    out = {}
    for k, v in base.items():
        d = (seed * 7 + ord(k[0])) % 11 - 5
        out[k] = max(5, min(95, v + d))
    return out


def E(year, title, desc, choices, flag=None, month=None, outcome=None):
    """事件元组：(年, 标题, 描述, [5选项], 主选项旗标|None, 月|None, 史实结局|None)

    month / outcome 为后加的可选位，旧调用（5 元组写法）完全兼容。
    """
    return (year, title, desc, choices, flag, month, outcome)


def emp(id, period, name, title, start, end, eval_, bg, era_ctx, premise, profile, events, tier=None):
    base = PROFILES.get(profile, PROFILES["balanced"])
    seed = sum(ord(c) for c in id)
    initStats = _jitter(base, seed)
    civ = id.split("_")[0]
    n0 = len(events)
    # 历史事件 → 事件对象
    evs = [_conv_event(id, yr, t_, d, ch, fl, i, seed, month=mo, outcome=oc)
           for i, (yr, t_, d, ch, fl, mo, oc) in enumerate(events)]
    # 决策密度补足：原事件偏少时，注入本文明「 recurring crisis 」通用事件（flag 带 civ 前缀，避免冲突）
    gen_pool = CIV_GEN_EVENTS.get(civ, [])
    if gen_pool:
        need = min(2, max(0, 4 - n0))
        for k in range(need):
            g = gen_pool[(seed // 13 + k) % len(gen_pool)]
            # 【史实闸门 F2】通用事件年份必须落在在位区间内，
            # 旧式 start+1+k 会给短祚之君造出「崩后仍有事件」。
            yr = g[0] if g[0] else _clamp_year(start + 1 + k, start, end)
            # 【史实闸门 F1】按「文明 × 时代」解析模板名与选项，消除时代错置
            gt, gd, go, gc = resolve_layer(g[1], g[2], _clamp_year(yr, start, end), g[3])
            evs.append(_conv_event(id, yr, gt, gd, gc, g[4], len(evs), seed, outcome=go))
    # 声线与常驻班底（统一剧情软注入素材；对齐 index.html VOICE_TAG_VARIANT 三值）
    vt = VOICE_BY_PROFILE.get(profile) or CIV_VOICE.get(civ, "质朴")
    tmpl = CIV_CAST.get(civ, [])
    n_cast = 3 if (tier or n0 >= 5) else 2
    cast = [dict(tmpl[(seed % len(tmpl) + k) % len(tmpl)]) for k in range(n_cast)] if tmpl else []
    return {
        "id": id, "civilization": civ, "dynasty": period,
        "name": name, "templeName": title, "reignStart": start, "reignEnd": end,
        "evaluation": eval_, "background": bg, "eraContext": era_ctx,
        "reignPremise": premise, "voiceTag": vt, "era": period,
        "initStats": initStats, "tier": tier or ("A" if n0 >= 5 else "B"),
        "cast": cast, "events": evs,
    }


