_SENT_SPLIT = re.compile(r'[。；;！!？?]')


def derive_outcome(desc, title):
    """从已核准的 description 末句派生史实结局；不新增史实断言，零风险。"""
    if not desc:
        return title or ''
    parts = [p.strip() for p in _SENT_SPLIT.split(desc) if p.strip()]
    if not parts:
        return title or ''
    tail = parts[-1]
    if len(tail) < 6 and len(parts) >= 2:
        tail = parts[-2] + '，' + tail
    tail = re.sub(r'^(公元)?[前]?\d+年[，,]?', '', tail)
    tail = re.sub(r'^\d+月[，,]?', '', tail)
    if len(tail) > 30:
        tail = tail[:30]
    return tail.rstrip('，,、')


def _clamp_year(y, start, end):
    """把年份钳制回在位区间，杜绝「君主已崩仍有事件」。"""
    if not isinstance(y, int):
        return y
    if isinstance(start, int) and isinstance(end, int) and end >= start:
        return max(start, min(end, y))
    if isinstance(start, int):
        return max(start, y)
    return y


def resolve_layer(title, desc, year, choices=None):
    """按年代解析通用模板名与选项。未登记的模板原样返回（并补一条派生结局）。

    返回 (title, description, historicalOutcome, choices)。
    """
    layers = LAYERS.get(title)
    if not layers or not isinstance(year, int):
        return title, desc, derive_outcome(desc, title), choices
    for L in layers:
        lo, hi, nt, nd, no = L[0], L[1], L[2], L[3], L[4]
        nc = L[5] if len(L) > 5 else None
        if lo <= year <= hi:
            return nt, nd, no, (list(nc) if nc else choices)
    return title, desc, derive_outcome(desc, title), choices


def postprocess(emperors):
    """统一史实后处理：精修覆盖 → 年份钳制 → 同年分月 → 结局兜底 → 按年月排序。

    返回 (n_override, n_clamp, n_outcome) 供 main 打印回归数字。
    """
    n_ov = n_clamp = n_out = 0
    for e in emperors:
        s, t = e.get('reignStart'), e.get('reignEnd')
        evs = e.get('events') or []
        for ev in evs:
            ov = EVENT_OVERRIDES.get(ev.get('id'))
            if ov:
                for k, v in ov.items():
                    ev[k] = v
                n = len(ev.get('choices') or [])
                for key in ('relationDeltas', 'branches'):
                    arr = ev.get(key)
                    if isinstance(arr, list) and len(arr) != n:
                        print('  [WARN] %s %s 长度 %d != choices %d' % (ev.get('id'), key, len(arr), n))
                n_ov += 1
            y = ev.get('year')
            ny = _clamp_year(y, s, t)
            if ny != y:
                ev['year'] = ny
                n_clamp += 1
            if not (ev.get('historicalOutcome') or '').strip():
                ev['historicalOutcome'] = derive_outcome(ev.get('description'), ev.get('title'))
                n_out += 1
        # 同年多事件以 month 排开，避免同年同月堆叠
        buckets = {}
        for ev in evs:
            if isinstance(ev.get('year'), int):
                buckets.setdefault(ev['year'], []).append(ev)
        for _y, group in buckets.items():
            if len(group) > 1:
                step = max(1, 12 // len(group))
                for k, ev in enumerate(group):
                    if ev.get('month') in (None, 0):
                        ev['month'] = min(12, 1 + k * step)
        evs.sort(key=lambda x: (x.get('year') if isinstance(x.get('year'), int) else 0,
                                x.get('month') if isinstance(x.get('month'), int) else 0))
    return n_ov, n_clamp, n_out


def _conv_event(eid, yr, title_, desc, choices, flag, idx, seed, month=None, outcome=None):
    """把 E() 元组转成带 branches / relationDeltas 的事件对象（与 emp 内联逻辑一致）。"""
    branches = []
    for i in range(5):
        branches.append({"setFlags": [flag]} if (i == 0 and flag) else {})
    rel = []
    for i in range(5):
        f = FACTIONS[(i + (seed % 4)) % 4]
        rel.append({f: 2 if i % 2 == 0 else -1})
    return {
        "year": yr, "month": month, "title": title_, "description": desc,
        "historicalChoice": 0, "choices": list(choices),
        # 【史实闸门 F3】结局缺省从 description 末句派生，不再留空
        "historicalOutcome": outcome or derive_outcome(desc, title_),
        "id": f"{eid}_e{idx}",
        "relationDeltas": rel, "branches": branches,
    }


