def write_country(cid, group, periods, emperors):
    # 【史实闸门】写盘前统一过一道后处理，保证重生成不会退回审查前的状态
    n_ov, n_clamp, n_out = postprocess(emperors)
    data = {"group": group, "dynasties": periods, "emperors": emperors}
    fname = {"us": "09-us.json", "uk": "10-uk.json", "rome": "11-rome.json", "ru": "12-ru.json"}[cid]
    path = os.path.join(OUT_DIR, fname)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    total_events = sum(len(e["events"]) for e in emperors)
    print(f"{fname}: {len(emperors)} 位首领, {total_events} 则事件 "
          f"(精修覆盖 {n_ov} / 年份钳制 {n_clamp} / 结局兜底 {n_out})")
    return emperors


def selfcheck(all_emps):
    """回归自检：越界事件 / 空结局 / 时代错置残留 / 选项数组错位，任一非零即报警。"""
    bad_year, bad_out, bad_len = [], [], []
    for e in all_emps:
        s, t = e.get('reignStart'), e.get('reignEnd')
        for ev in e.get('events') or []:
            y = ev.get('year')
            if isinstance(y, int) and isinstance(s, int) and isinstance(t, int) and not (s <= y <= t):
                bad_year.append(f"{e['id']} {ev['id']} y={y} 不在 {s}~{t}")
            if not (ev.get('historicalOutcome') or '').strip():
                bad_out.append(f"{e['id']} {ev['id']}")
            n = len(ev.get('choices') or [])
            for key in ('relationDeltas', 'branches'):
                arr = ev.get(key)
                if isinstance(arr, list) and len(arr) != n:
                    bad_len.append(f"{e['id']} {ev['id']} {key}={len(arr)} choices={n}")
    # 时代错置残留：模板原名若还留在产物里，说明分层没覆盖到
    stale = []
    for e in all_emps:
        for ev in e.get('events') or []:
            layers = LAYERS.get(ev.get('title'))
            if not layers:
                continue
            y = ev.get('year')
            if not isinstance(y, int):
                continue
            hit = next((L for L in layers if L[0] <= y <= L[1]), None)
            if hit and hit[2] != ev.get('title'):
                stale.append(f"{e['id']} {ev['id']} 《{ev['title']}》 y={y} 应为《{hit[2]}》")
            # 选项也须随层更换，否则时代错置只是从标题挪进了选项里
            if hit and len(hit) > 5 and hit[5] and list(hit[5]) != list(ev.get('choices') or []):
                stale.append(f"{e['id']} {ev['id']} 《{ev['title']}》 y={y} 选项未随层更换")
    print("\n=== 回归自检 ===")
    print(f"  事件越出在位区间 : {len(bad_year)}")
    for x in bad_year[:10]:
        print("    " + x)
    print(f"  historicalOutcome 空缺 : {len(bad_out)}")
    for x in bad_out[:10]:
        print("    " + x)
    print(f"  选项/关系/分支数组错位 : {len(bad_len)}")
    for x in bad_len[:10]:
        print("    " + x)
    print(f"  时代错置残留 : {len(stale)}")
    for x in stale[:10]:
        print("    " + x)
    ok = not (bad_year or bad_out or bad_len or stale)
