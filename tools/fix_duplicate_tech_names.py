changes = 0
for n in nodes:
    nid = n['id']
    if nid in rename_map:
        new_name, new_suffix = rename_map[nid]
        old_name = n['name']
        n['name'] = new_name
        # 更新 desc：保持 "branchName·ageName：" 前缀，替换后面的内容
        prefix = f"{n['branchName']}·{n['ageName']}："
        n['desc'] = prefix + new_name + "。" + new_suffix
        changes += 1
        print(f"  {nid:20s}  '{old_name}'  →  '{new_name}'")

print(f"\n共重命名 {changes} 个节点")

