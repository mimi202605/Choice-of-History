// ---------- 组装并写入 ----------
function load(file) {
  return JSON.parse(fs.readFileSync(path.join(DIR, file), "utf8"));
}
function save(file, data) {
  fs.writeFileSync(path.join(DIR, file), JSON.stringify(data, null, 2), "utf8");
}

const file01 = load("01-xia-shang-zhou-qin.json");
const file02 = load("02-han-xin-sanguo.json");

// 收集既有 id，防止重复
const existingIds = new Set();
for (const f of [file01, file02]) for (const e of f.emperors) existingIds.add(e.id);

const additions = [];
for (const k of ZHOU) additions.push(buildZhou(k));
for (const e of QIN_EXTRA) additions.push(e);
for (const e of WEI) additions.push(e);
for (const e of WU) additions.push(e);

// 校验 id 唯一
const clash = additions.filter((a) => existingIds.has(a.id));
if (clash.length) {
  console.error("❌ 以下 id 与现有数据冲突，已中止：", clash.map((c) => c.id).join(", "));
  process.exit(1);
}

// 追加：周/秦 -> file01；三国 -> file02
const zhouQin = additions.filter((a) => a.dynasty === "周" || a.dynasty === "秦");
const threeK = additions.filter((a) => a.dynasty === "三国");
file01.emperors = file01.emperors.concat(zhouQin);
file02.emperors = file02.emperors.concat(threeK);

save("01-xia-shang-zhou-qin.json", file01);
