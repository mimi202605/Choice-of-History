// ---------- 工具 ----------
// 派系：宗室 / 士大夫 / 边将 / 商贾
function rd(spec) {
  const a = [{}, {}, {}, {}, {}];
  if (spec) for (const k in spec) a[+k] = spec[k];
  return a;
}
function branches(empId, evIdx, n) {
  return Array.from({ length: n }, (_, i) => ({
    setFlags: [`did_${empId}_e${evIdx}_${i}`],
    clearFlags: [],
    nextEventId: null,
  }));
}
// 构造单条事件（choices 固定5项，branches 与之对齐）
function ev(empId, evIdx, year, title, desc, choices, outcome, hist, rdSpec, opts) {
  opts = opts || {};
  return {
    id: `${empId}_e${evIdx}`,
    year,
    month: null,
    title,
    description: desc,
    historicalChoice: hist == null ? -1 : hist,
    choices,
    historicalOutcome: outcome || "",
    relationDeltas: rd(rdSpec),
    ...(opts.major ? { tier: "major", gating: {} } : {}),
    branches: branches(empId, evIdx, choices.length),
  };
}
function emperor(o) {
  return {
    id: o.id,
    dynasty: o.dynasty,
    name: o.name,
    templeName: o.templeName,
    reignStart: o.start,
    reignEnd: o.end,
    evaluation: o.eval,
    background: o.bg,
    initStats: o.init,
    eraContext: o.era,
    tier: o.tier || "B",
    events: o.events,
  };
}

