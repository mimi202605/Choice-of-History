def build_tree():
    nodes = []
    seen_names = {}
    for br in BRANCHES:
        grid = BRANCH_NAMES[br["id"]]
        for ai, age_names in enumerate(grid):        # ai: 0..13
            age = ai + 1
            for ti, name in enumerate(age_names):     # ti: 0..8
                if name is None:
                    continue
                # 名称全局唯一性保护
                key = name
                if key in seen_names:
                    name = f"{name}·{br['id']}{age:02d}{ti:02d}"
                seen_names[key] = True

                tid = f"{br['id']}_{age:02d}_{ti:02d}"
                # 前置：同分支上一时代同轨道
                prereq = []
                if age > 1:
                    prereq.append(f"{br['id']}_{age-1:02d}_{ti:02d}")
                # 满级与单价随时代递增
                max_level = 3 if age <= 3 else (4 if age <= 7 else 5)
                cost_pts = 2 + age          # 解锁第 1 级的科技点数
                per_level = 1 + (age // 4)  # 每级递增点数
                # 属性增益（每级）
                a0, a1 = br["attrs"]
                special = br["specials"][ti]
                base_bonus = {a0: 1, a1: 1}
                node = {
                    "id": tid,
                    "name": name,
                    "branch": br["id"],
                    "branchName": br["name"],
                    "track": br["tracks"][ti],
                    "age": age,
                    "ageName": AGE_BY_ID[age]["name"],
                    "era": AGE_BY_ID[age]["era"],
                    "desc": f"{br['name']}·{AGE_BY_ID[age]['name']}：{name}。",
                    "prereq": prereq,
                    "maxLevel": max_level,
                    "cost": {"base": cost_pts, "perLevel": per_level},
                    "bonusPerLevel": base_bonus,
                    "special": special,
                    "specialAttr": SPECIAL_TO_ATTR[special],
                    "functionDesc": SPECIAL_DESC[special],
                }
                # 按文明显示名覆盖（foreign=美/英/俄通用，rome=罗马；cn 用 node.name）
                _bciv = branch_civ(br["id"]) or {"foreign": br["name"], "rome": br["name"]}
                _tciv = track_civ(br["id"], br["tracks"][ti]) or {"foreign": br["tracks"][ti], "rome": br["tracks"][ti]}
                node["civBranch"] = _bciv
                node["trackNames"] = _tciv
                node["names"] = node_civ(tid, name)
                nodes.append(node)
    return nodes

# ---------------------------------------------------------------------------
# 6. 生成朝代预设（皇帝初始科技树）
# ---------------------------------------------------------------------------
def build_presets(nodes):
    by_id = {n["id"]: n for n in nodes}
    def coord(branch, age, track):
        return f"{branch}_{age:02d}_{track:02d}"

    presets = {}
    for dynasty, era_level in DYNASTY_ERA.items():
        techs = {}
        for n in nodes:
            if n["branch"] == "occ" and n["age"] > 5:
                # 格物穷理：先进哲学/方法论仅预置到该朝代所处时代，更晚的节点不预置（玩家可主动研习）
                if era_level < n["age"]:
                    continue
            if n["age"] > era_level:
                continue
            track_idx = int(n["id"].split("_")[2])
            core = track_idx <= 2          # 前 3 条轨道为核心轨道
            if core:
                if n["age"] <= 2:
                    lvl = n["maxLevel"]                 # 根基满级
                elif n["age"] <= era_level - 1:
                    lvl = min(2, n["maxLevel"])
                else:
                    lvl = 1
            else:
                if n["age"] <= era_level - 2:
                    lvl = 1
                else:
                    continue
            techs[n["id"]] = lvl
        # 标志科技强化
        for (b, a, t) in SIGNATURE.get(dynasty, []):
            cid = coord(b, a, t)
            if cid in by_id:
                techs[cid] = max(techs.get(cid, 0), min(3, by_id[cid]["maxLevel"]))
        # 清理非法（id 不存在）
        techs = {k: v for k, v in techs.items() if k in by_id}
        presets[dynasty] = {
            "eraLevel": era_level,
            "eraName": AGE_BY_ID[era_level]["name"],
            "techCount": len(techs),
            "techs": techs,
        }
    return presets

# ---------------------------------------------------------------------------
# 7. 校验
# ---------------------------------------------------------------------------
def validate(nodes, presets):
    errs = []
    ids = [n["id"] for n in nodes]
    if len(ids) != len(set(ids)):
        errs.append("节点 id 重复")
    names = [n["name"] for n in nodes]
    dup = [x for x in set(names) if names.count(x) > 1]
    if dup:
        errs.append(f"节点名称重复: {dup[:10]}")
    if len(nodes) < 1000:
        errs.append(f"节点数 {len(nodes)} < 1000")
    # DAG 校验
    by_id = {n["id"]: n for n in nodes}
    def has_cycle(start, seen):
        for p in by_id[start]["prereq"]:
            if p in seen:
                return True
            if p in by_id and has_cycle(p, seen | {p}):
                return True
        return False
    for n in nodes:
        if has_cycle(n["id"], {n["id"]}):
            errs.append(f"前置环: {n['id']}")
            break
    for p in presets.values():
        for tid in p["techs"]:
            if tid not in by_id:
                errs.append(f"预设引用不存在节点: {tid}")
                break
    return errs

def main():
    nodes = build_tree()
    presets = build_presets(nodes)
    errs = validate(nodes, presets)
    if errs:
        print("校验失败:", errs)
