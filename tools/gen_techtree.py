def _load_overlay():
    p = os.path.join(os.path.dirname(__file__), "..", "data", "tech_names_overlay.json")
    try:
        with open(p, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return {"branches": {}, "tracks": {}, "nodes": {}}

OVERLAY = _load_overlay()

def _expand(val):
    """val: str | {foreign, rome} → {'foreign':.., 'rome':..}"""
    if isinstance(val, str):
        return {"foreign": val, "rome": val}
    return {"foreign": val.get("foreign", val.get("rome", "")),
            "rome": val.get("rome", val.get("foreign", ""))}

def branch_civ(bid):
    raw = OVERLAY.get("branches", {}).get(bid)
    if raw is None:
        return None
    return _expand(raw)

def track_civ(bid, cn_track):
    bt = OVERLAY.get("tracks", {}).get(bid, {})
    raw = bt.get(cn_track)
    if raw is None:
        return None
    return _expand(raw)

def node_civ(tid, cn_name):
    raw = OVERLAY.get("nodes", {}).get(tid)
    if raw is None:
        return {"foreign": cn_name, "rome": cn_name}
    if isinstance(raw, str):
        return {"foreign": raw, "rome": raw}
    return {"foreign": raw.get("foreign", cn_name), "rome": raw.get("rome", cn_name)}

